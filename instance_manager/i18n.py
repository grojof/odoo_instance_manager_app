"""Lightweight, modular UI translation.

English is the source language: the string in the code is already English, so
the default UI needs no translation. When Spanish is selected, translation
happens at a few display/input chokepoints (see ``ui``/``prompts``) plus ``tf``
for interpolated messages, so call sites barely change. Any string missing from
the catalog falls back to English, so partial translation degrades gracefully.

The catalog below is written English → Spanish, the direction it is read.
"""

from __future__ import annotations

_LANG = "en"


def set_language(lang: str) -> None:
    global _LANG
    _LANG = "es" if str(lang).lower().startswith("es") else "en"


def current_language() -> str:
    return _LANG


def t(text: str) -> str:
    """Translate an English UI string to the current language (English → Spanish)."""
    if _LANG == "en":
        return text
    return _ES.get(text, text)


def tf(template: str, *args: object, **kwargs: object) -> str:
    """Translate a message template, then fill its ``{}``/``{name}`` placeholders.

    The English template is the catalog key, so interpolated messages translate
    too — e.g. ``tf("Already exists {}", path)`` looks up ``"Already exists {}"``.
    """
    return t(template).format(*args, **kwargs)


